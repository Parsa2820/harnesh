package shell

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// definitionsCheckTimeout bounds the trial run of the generated definitions.
const definitionsCheckTimeout = 2 * time.Second

// definitions makes the original shell's aliases and functions available to
// !commands.
//
// Those live in rc files, which a shell only reads when it is interactive,
// while !commands run in "<shell> -c". Running them in an interactive shell
// instead would re-run the whole rc file for every command, with all its
// side effects. Instead, the definitions captured once at startup are written
// to a private file, and each command's shell is pointed at it through the
// one startup file a non-interactive shell does read: $ZDOTDIR/.zshenv for
// zsh, $BASH_ENV for bash.
type definitions struct {
	dir string
	env []string
}

// newDefinitions writes the startup files for the definitions in profile. It
// returns nil when there is nothing to load or the shell has no suitable
// startup file; !commands then run exactly as they would in a script.
func newDefinitions(shellPath, shellKind string, profile shellProfile) *definitions {
	if !profile.probed || (profile.functions == "" && profile.aliases == "") {
		return nil
	}
	var build func(d *definitions, source string) error
	switch shellKind {
	case "zsh":
		build = (*definitions).writeZsh
	case "bash":
		build = (*definitions).writeBash
	default:
		return nil
	}

	dir, err := os.MkdirTemp("", "harnesh-")
	if err != nil {
		return nil
	}
	d := &definitions{dir: dir}

	// Shells do not always print a definition in a form they can read back.
	// If the full set does not load cleanly, settle for the aliases, which
	// have a far simpler syntax, rather than have every command start with
	// an error message.
	candidates := []string{
		definitionsSource(shellKind, profile.options, profile.functions, profile.aliases),
		definitionsSource(shellKind, "", "", profile.aliases),
	}
	for i, source := range candidates {
		if source == "" || (i > 0 && source == candidates[i-1]) {
			continue
		}
		if err := build(d, source); err != nil {
			break
		}
		if d.loadsCleanly(shellPath, shellKind) {
			return d
		}
	}
	d.Close()
	return nil
}

// Env returns the environment entries that make a "<shell> -c" child load the
// definitions.
func (d *definitions) Env() []string {
	return d.env
}

// Close removes the generated files.
func (d *definitions) Close() {
	_ = os.RemoveAll(d.dir)
}

func (d *definitions) sourcePath() string {
	return filepath.Join(d.dir, "definitions")
}

// writeZsh points zsh at a private ZDOTDIR whose .zshenv first puts things
// back the way they were, so that the user's own .zshenv still runs and no
// shell started by the command ever sees the private directory.
func (d *definitions) writeZsh(source string) error {
	var env strings.Builder
	env.WriteString("# Generated by harnesh: loads the original shell's aliases and functions into !commands.\n")
	if original, ok := os.LookupEnv("ZDOTDIR"); ok {
		fmt.Fprintf(&env, "export ZDOTDIR=%s\n", shellQuote(original))
	} else {
		env.WriteString("unset ZDOTDIR\n")
	}
	env.WriteString("[[ -r ${ZDOTDIR:-$HOME}/.zshenv ]] && source ${ZDOTDIR:-$HOME}/.zshenv\n")
	fmt.Fprintf(&env, "source %s\n", shellQuote(d.sourcePath()))

	d.env = []string{"ZDOTDIR=" + d.dir}
	return d.write(".zshenv", env.String(), source)
}

// writeBash does the same through BASH_ENV, which names a file bash sources
// before running a script or a -c command.
func (d *definitions) writeBash(source string) error {
	var env strings.Builder
	env.WriteString("# Generated by harnesh: loads the original shell's aliases and functions into !commands.\n")
	if original, ok := os.LookupEnv("BASH_ENV"); ok {
		fmt.Fprintf(&env, "export BASH_ENV=%s\n", shellQuote(original))
		env.WriteString("[ -r \"$BASH_ENV\" ] && . \"$BASH_ENV\"\n")
	} else {
		env.WriteString("unset BASH_ENV\n")
	}
	fmt.Fprintf(&env, ". %s\n", shellQuote(d.sourcePath()))

	d.env = []string{"BASH_ENV=" + filepath.Join(d.dir, "env")}
	return d.write("env", env.String(), source)
}

func (d *definitions) write(envName, env, source string) error {
	if err := os.WriteFile(d.sourcePath(), []byte(source), 0o600); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(d.dir, envName), []byte(env), 0o600)
}

// loadsCleanly reports whether a pristine shell (no rc files) reads the
// definitions back without complaint.
func (d *definitions) loadsCleanly(shellPath, shellKind string) bool {
	ctx, cancel := context.WithTimeout(context.Background(), definitionsCheckTimeout)
	defer cancel()

	args := []string{"-f", "-c", `source "$1"`, "harnesh", d.sourcePath()}
	if shellKind == "bash" {
		args = []string{"--noprofile", "--norc", "-c", `. "$1"`, "harnesh", d.sourcePath()}
	}
	var stderr bytes.Buffer
	cmd := exec.CommandContext(ctx, shellPath, args...)
	cmd.Env = withoutEnv(os.Environ(), "BASH_ENV")
	cmd.Stderr = &stderr
	return cmd.Run() == nil && stderr.Len() == 0
}

// definitionsSource assembles shell source from the probed sections. The order
// matters: options affect how function bodies are parsed (bash's extglob), and
// an alias defined before a function of the same name would be expanded in
// the function's definition.
func definitionsSource(shellKind, options, functions, aliases string) string {
	var b strings.Builder
	section := func(text string) {
		if text = strings.TrimSpace(text); text != "" {
			b.WriteString(text)
			b.WriteString("\n")
		}
	}
	switch shellKind {
	case "zsh":
		section(zshOptionCommands(options))
		section(functions)
		section(aliases)
	case "bash":
		section(options)
		section(functions)
		if strings.TrimSpace(aliases) != "" {
			// Bash only expands aliases in interactive shells by default.
			section("shopt -s expand_aliases")
			section(bashAliasCommands(aliases))
		}
	}
	return b.String()
}

// zshOptionsNotCarried lists options that must keep the value a "zsh -c"
// shell starts with, whatever the interactive shell had: they either describe
// the session rather than the language, or would change how a command line
// behaves in ways that only make sense at a prompt.
var zshOptionsNotCarried = map[string]bool{
	"correct":        true,
	"correctall":     true,
	"errexit":        true,
	"errreturn":      true,
	"exec":           true,
	"globalrcs":      true,
	"interactive":    true,
	"localoptions":   true,
	"localpatterns":  true,
	"localtraps":     true,
	"login":          true,
	"monitor":        true,
	"notify":         true,
	"printexitvalue": true,
	"privileged":     true,
	"rcs":            true,
	"restricted":     true,
	"shinstdin":      true,
	"singlecommand":  true,
	"sourcetrace":    true,
	"verbose":        true,
	"xtrace":         true,
	"zle":            true,
}

// zshOptionCommands turns the probe's "name on|off" lines into setopt and
// unsetopt commands.
func zshOptionCommands(options string) string {
	var b strings.Builder
	for _, line := range strings.Split(options, "\n") {
		name, state, ok := strings.Cut(strings.TrimSpace(line), " ")
		if !ok || !isShellWord(name) || zshOptionsNotCarried[name] {
			continue
		}
		switch state {
		case "on":
			b.WriteString("setopt " + name + "\n")
		case "off":
			b.WriteString("unsetopt " + name + "\n")
		}
	}
	return b.String()
}

// bashAliasCommands adapts "alias -p" output for reading back. Older versions
// of bash print an alias whose name starts with "-" in a form the alias
// builtin then takes for an option.
func bashAliasCommands(aliases string) string {
	lines := strings.Split(aliases, "\n")
	for i, line := range lines {
		if strings.HasPrefix(line, "alias -") && !strings.HasPrefix(line, "alias -- ") {
			lines[i] = "alias -- " + strings.TrimPrefix(line, "alias ")
		}
	}
	return strings.Join(lines, "\n")
}

// isShellWord reports whether s consists only of letters, digits, and
// underscores.
func isShellWord(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

// shellQuote quotes s as a single word for a POSIX shell.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// withoutEnv returns env without the entries for key.
func withoutEnv(env []string, key string) []string {
	out := make([]string, 0, len(env))
	for _, entry := range env {
		if !strings.HasPrefix(entry, key+"=") {
			out = append(out, entry)
		}
	}
	return out
}
